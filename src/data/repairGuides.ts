export const REPAIR_GUIDE_BY_ID: Record<string, RepairGuide> = Object.fromEntries(
  REPAIR_GUIDES.map((guide) => [guide.id, guide]),
)

export function getRepairGuide(id: string): RepairGuide | undefined {
  return REPAIR_GUIDE_BY_ID[id]
}

export function guidesForComponents(componentIds: string[]): RepairGuide[] {
  const unique = [...new Set(componentIds)]
  return unique
    .map((id) => REPAIR_GUIDE_BY_ID[id])
    .filter((guide): guide is RepairGuide => Boolean(guide))
}

export function searchRepairGuides(query: string): RepairGuide[] {
  const q = query
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
  if (!q) return REPAIR_GUIDES
  return REPAIR_GUIDES.filter((guide) => {
    const haystack = `${guide.name} ${guide.system} ${guide.summary} ${guide.ifixQuery}`
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
    return haystack.includes(q)
  })
}
